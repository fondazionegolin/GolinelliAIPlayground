#!/usr/bin/env node
/**
 * Generate the platform's icons from the official free Untitled UI line collection.
 * Add ExportName → UntitledName to icon-map.untitled.json, then run `npm run icons`.
 * Only mapped SVG bodies are emitted, so no icon font or full library is shipped.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import * as icons from '@untitledui/icons'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const map = JSON.parse(readFileSync(join(root, 'src/components/icons/icon-map.untitled.json'), 'utf8'))
const bodies = new Map()
for (const name of new Set(Object.values(map))) {
  if (!icons[name]) throw new Error(`Unknown Untitled UI icon: ${name}`)
  const svg = renderToStaticMarkup(createElement(icons[name]))
  const body = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '')
  if (!body || body === svg) throw new Error(`Invalid Untitled UI SVG: ${name}`)
  bodies.set(name, body)
}
const lines = [
  '// AUTO-GENERATED by scripts/generate-icons.mjs — edit icon-map.untitled.json and run `npm run icons`.',
  '// Untitled UI Icons (https://www.untitledui.com/free-icons), free line style. See UNTITLED-LICENSE.txt.',
  "import { createIcon } from './createIcon'",
  '',
  ...[...bodies].map(([name, body]) => `const G_${name} = ${JSON.stringify(body)}`),
  '',
  ...Object.entries(map).sort(([a], [b]) => a.localeCompare(b))
    .map(([name, glyph]) => `export const ${name} = createIcon('${name}', G_${glyph})`),
  '',
]
writeFileSync(join(root, 'src/components/icons/icons.generated.tsx'), lines.join('\n'))
console.log(`Generated ${Object.keys(map).length} icons (${bodies.size} Untitled UI SVGs).`)

// The coding preview runs in an isolated HTML document rather than React.
writeFileSync(join(root, 'src/components/icons/inspector-sparkles.generated.ts'),
  '// AUTO-GENERATED by scripts/generate-icons.mjs; Untitled UI, see UNTITLED-LICENSE.txt.\nexport default ' +
  JSON.stringify(renderToStaticMarkup(createElement(icons[map.Sparkles], { size: 12 }))) + '\n')
