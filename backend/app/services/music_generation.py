"""Music generation model chosen by the admin (role ``audio.music`` in Admin → Modelli).

ElevenLabs Music stays the default (handled in endpoints/voice_lab.py with the rest of ElevenLabs). Google Lyria runs
through OpenRouter: audio output there requires a streamed chat completion; the chunks carry base64 MP3 data and the
final chunk carries the real cost, which is what we bill. ACE-Step (open source, very cheap, experimental) runs on
Runware ("audioInference"), which also returns the real cost.
"""
from __future__ import annotations

import base64
import json
import logging
import math
from typing import Optional

import httpx
from fastapi import HTTPException

from app.core.config import settings
from app.core.pricing import USD_TO_EUR
from app.services import model_roles
from app.services.credit_service import to_credits

logger = logging.getLogger(__name__)
ROLE = "audio.music"
OPENROUTER_URL = "https://openrouter.ai/api/v1/chat/completions"
PRICING_SOURCE = "https://openrouter.ai/models"

# Verified 2026-11-09 with a real generation (clip: MP3, ~30 s, $0.04). Pro: one full song per request.
LYRIA = {
    "google/lyria-3-clip-preview": {"label": "Lyria 3 Clip", "usd": 0.04, "fixed_seconds": 30, "max_seconds": 30},
    "google/lyria-3-pro-preview": {"label": "Lyria 3 Pro", "usd": 0.08, "fixed_seconds": None, "max_seconds": 180},
}


# Verified 2026-11-09 on Runware (30 s MP3 in 3-7 s; XL Turbo also sings Italian lyrics). usd = observed cost per track.
RUNWARE = {
    "runware:ace-step@v1.5-xl-turbo": {"label": "ACE-Step 1.5 XL Turbo (sperimentale)", "usd": 0.002, "min_seconds": 30, "max_seconds": 300},
    "runware:ace-step@v1.5-turbo": {"label": "ACE-Step 1.5 Turbo (sperimentale)", "usd": 0.004, "min_seconds": 30, "max_seconds": 300},
    "runware:ace-step@v1.5-xl-sft": {"label": "ACE-Step 1.5 XL SFT (sperimentale, più curato)", "usd": 0.008, "min_seconds": 30, "max_seconds": 300},
}


def spec_of(model: str) -> dict:
    return LYRIA.get(model) or RUNWARE[model]


def current() -> dict:
    """The model the platform uses for music right now, with the limits the UI must show."""
    provider, model = model_roles.pair_for(ROLE)
    if provider == "openrouter" and model in LYRIA:
        spec = LYRIA[model]
        return {"provider": provider, "model": model, "label": f"{spec['label']} · Google", "fixed_seconds": spec["fixed_seconds"],
                "max_seconds": spec["max_seconds"], "price_note": f"${spec['usd']:g} a brano"}
    if provider == "runware" and model in RUNWARE:
        spec = RUNWARE[model]
        return {"provider": provider, "model": model, "label": spec["label"], "fixed_seconds": None, "min_seconds": spec["min_seconds"],
                "max_seconds": spec["max_seconds"], "price_note": f"circa ${spec['usd']:g} a brano"}
    return {"provider": "elevenlabs", "model": "music_v1", "label": "ElevenLabs Music", "fixed_seconds": None,
            "max_seconds": 600, "price_note": "$0.15 al minuto"}


def uses_external() -> bool:
    """True when music is not generated by ElevenLabs (Lyria via OpenRouter, ACE-Step via Runware)."""
    return current()["provider"] in ("openrouter", "runware")


def quote(model: str, usd: Optional[float] = None) -> dict:
    """Same shape as voice_lab_billing.quote, priced per track (the real OpenRouter cost when known)."""
    spec = spec_of(model)
    usd = round(float(usd if usd is not None and math.isfinite(usd) and usd >= 0 else spec["usd"]), 6)
    cost = round(usd * USD_TO_EUR, 10)
    return {"action": "music", "cost": cost, "credits": to_credits(cost), "usd": usd, "quantity": 1, "unit": "tracks",
            "rate_usd": spec["usd"], "usd_to_eur": USD_TO_EUR, "source": PRICING_SOURCE, "pricing_basis": "per_track_real_cost",
            "model": model}


def _prompt(text: str, seconds: int, instrumental: bool, fixed: Optional[int]) -> str:
    parts = [text.strip()]
    if not fixed:
        parts.append(f"Duration: about {seconds} seconds.")
    if instrumental:
        parts.append("Instrumental only, no vocals.")
    return "\n\n".join(parts)


async def generate_lyria(model: str, text: str, seconds: int, instrumental: bool) -> tuple[bytes, str, Optional[float]]:
    """(audio bytes, mime type, real cost in USD) from Lyria via OpenRouter."""
    if not settings.OPENROUTER_API_KEY:
        raise HTTPException(503, "Chiave OpenRouter non configurata: scegli un altro modello musicale in Admin → Modelli")
    spec = LYRIA[model]
    chunks: list[str] = []
    cost: Optional[float] = None
    payload = {"model": model, "modalities": ["audio", "text"], "stream": True, "audio": {"format": "mp3"},
               "messages": [{"role": "user", "content": _prompt(text, min(seconds, spec["max_seconds"]), instrumental, spec["fixed_seconds"])}]}
    try:
        async with httpx.AsyncClient(timeout=httpx.Timeout(300, connect=20)) as client:
            async with client.stream("POST", OPENROUTER_URL, json=payload,
                                     headers={"Authorization": f"Bearer {settings.OPENROUTER_API_KEY}"}) as response:
                if response.status_code != 200:
                    body = (await response.aread())[:600].decode("utf-8", "replace")
                    logger.warning("OpenRouter music %s -> HTTP %s: %s", model, response.status_code, body)
                    if response.status_code == 402:
                        raise HTTPException(503, "OpenRouter: credito esaurito per la generazione musicale.")
                    if response.status_code == 429:
                        raise HTTPException(503, "Lyria è occupato in questo momento: riprova tra poco.")
                    if response.status_code == 400 and "safety" in body.lower():
                        raise HTTPException(422, "La descrizione è stata rifiutata dai filtri di Lyria: riformulala.")
                    raise HTTPException(502, "La generazione musicale non è riuscita. Riprova.")
                async for line in response.aiter_lines():
                    if not line.startswith("data: ") or line == "data: [DONE]":
                        continue
                    try:
                        event = json.loads(line[6:])
                    except ValueError:
                        continue
                    if event.get("error"):
                        logger.warning("OpenRouter music stream error: %s", str(event["error"])[:300])
                        raise HTTPException(502, "La generazione musicale si è interrotta. Riprova.")
                    if event.get("usage", {}).get("cost") is not None:
                        cost = float(event["usage"]["cost"])
                    for choice in event.get("choices", []):
                        audio = (choice.get("delta") or {}).get("audio") or {}
                        if audio.get("data"):
                            chunks.append(audio["data"])
    except httpx.HTTPError as exc:
        logger.warning("OpenRouter music request failed: %s", exc)
        raise HTTPException(502, "Lyria non risponde: riprova tra poco.") from exc
    data = base64.b64decode("".join(chunks)) if chunks else b""
    if len(data) < 1000:
        raise HTTPException(502, "Lyria non ha restituito audio: riprova o riformula la descrizione.")
    return data, "audio/mpeg", cost


async def generate_runware(model: str, text: str, seconds: int, instrumental: bool) -> tuple[bytes, str, Optional[float]]:
    """(audio bytes, mime type, real cost in USD) from an ACE-Step model on Runware."""
    import uuid
    from app.services.runware_service import RunwareError, runware_service
    if not runware_service.configured:
        raise HTTPException(503, "Chiave Runware non configurata: scegli un altro modello musicale in Admin → Modelli")
    spec = RUNWARE[model]
    prompt = text.strip() + (", instrumental, no vocals" if instrumental else "")
    task = {"taskType": "audioInference", "taskUUID": str(uuid.uuid4()), "model": model, "positivePrompt": prompt[:3000],
            "duration": max(spec["min_seconds"], min(int(seconds), spec["max_seconds"])), "outputType": "URL", "outputFormat": "MP3",
            "includeCost": True, "deliveryMethod": "sync", "numberResults": 1}
    try:
        payload = await runware_service._post([task], timeout=300.0)
        item = (payload.get("data") or [{}])[0]
        if not item.get("audioURL"):
            raise HTTPException(502, "Il modello musicale non ha restituito audio: riprova.")
        data = await runware_service.download(item["audioURL"])
    except RunwareError as exc:
        logger.warning("Runware music %s failed: %s", model, exc)
        raise HTTPException(502, f"Generazione musicale non riuscita: {str(exc)[:160]}") from exc
    except httpx.HTTPError as exc:
        raise HTTPException(502, "Il servizio musicale non risponde: riprova tra poco.") from exc
    if len(data) < 1000:
        raise HTTPException(502, "Il modello musicale non ha restituito audio: riprova.")
    cost = item.get("cost")
    return data, "audio/mpeg", float(cost) if cost is not None else None


async def generate(model: str, text: str, seconds: int, instrumental: bool) -> tuple[bytes, str, Optional[float]]:
    if model in RUNWARE:
        return await generate_runware(model, text, seconds, instrumental)
    return await generate_lyria(model, text, seconds, instrumental)
